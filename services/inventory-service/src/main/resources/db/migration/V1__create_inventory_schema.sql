-- inventory-service schema (Oracle source of truth).
-- Written in the portable subset of Oracle SQL that H2 (MODE=Oracle) also accepts, so the same
-- migrations run in fast unit-level tests and against real Oracle in Testcontainers integration tests.

CREATE TABLE flight (
    id                 NUMBER(19)        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_number      VARCHAR2(8)       NOT NULL,
    origin             CHAR(3)           NOT NULL,
    destination        CHAR(3)           NOT NULL,
    departure_time     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    arrival_time       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    aircraft_type      VARCHAR2(16)      NOT NULL,
    base_fare_amount   NUMBER(12, 2)     NOT NULL,
    currency           CHAR(3)           NOT NULL,
    status             VARCHAR2(16)      NOT NULL,
    creation_key       VARCHAR2(64),
    created_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version            NUMBER(19)        DEFAULT 0 NOT NULL,
    CONSTRAINT ck_flight_status CHECK (status IN ('SCHEDULED', 'CANCELLED')),
    CONSTRAINT ck_flight_times CHECK (arrival_time > departure_time),
    CONSTRAINT ck_flight_route CHECK (origin <> destination),
    CONSTRAINT uq_flight_number_departure UNIQUE (flight_number, departure_time),
    CONSTRAINT uq_flight_creation_key UNIQUE (creation_key)
);

-- Flight search: route + departure window, the hottest read path.
CREATE INDEX ix_flight_route_departure ON flight (origin, destination, departure_time);

CREATE TABLE seat (
    id                 NUMBER(19)        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_id          NUMBER(19)        NOT NULL,
    seat_number        VARCHAR2(4)       NOT NULL,
    cabin_class        VARCHAR2(16)      NOT NULL,
    status             VARCHAR2(16)      NOT NULL,
    hold_id            VARCHAR2(36),
    held_until         TIMESTAMP(6) WITH TIME ZONE,
    booking_reference  VARCHAR2(6),
    -- Optimistic locking: every state change increments the version, so two concurrent holds of the
    -- same seat cannot both succeed (the loser's UPDATE ... WHERE version = ? matches no row).
    version            NUMBER(19)        DEFAULT 0 NOT NULL,
    CONSTRAINT fk_seat_flight FOREIGN KEY (flight_id) REFERENCES flight (id),
    CONSTRAINT uq_seat_flight_number UNIQUE (flight_id, seat_number),
    CONSTRAINT ck_seat_cabin CHECK (cabin_class IN ('ECONOMY', 'BUSINESS')),
    CONSTRAINT ck_seat_status CHECK (status IN ('AVAILABLE', 'HELD', 'BOOKED')),
    CONSTRAINT ck_seat_held CHECK (status <> 'HELD' OR (hold_id IS NOT NULL AND held_until IS NOT NULL)),
    CONSTRAINT ck_seat_booked CHECK (status <> 'BOOKED' OR booking_reference IS NOT NULL)
);

CREATE INDEX ix_seat_flight_status ON seat (flight_id, status);
CREATE INDEX ix_seat_hold ON seat (hold_id);
CREATE INDEX ix_seat_booking ON seat (flight_id, booking_reference);

CREATE TABLE seat_hold (
    id                  VARCHAR2(36)      PRIMARY KEY,
    flight_id           NUMBER(19)        NOT NULL,
    status              VARCHAR2(16)      NOT NULL,
    created_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    total_amount        NUMBER(12, 2)     NOT NULL,
    currency            CHAR(3)           NOT NULL,
    idempotency_key     VARCHAR2(64)      NOT NULL,
    request_fingerprint VARCHAR2(128)     NOT NULL,
    booking_reference   VARCHAR2(6),
    version             NUMBER(19)        DEFAULT 0 NOT NULL,
    CONSTRAINT fk_hold_flight FOREIGN KEY (flight_id) REFERENCES flight (id),
    CONSTRAINT uq_hold_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT ck_hold_status CHECK (status IN ('ACTIVE', 'CONFIRMED', 'RELEASED', 'EXPIRED'))
);

-- Expiry sweeper: "ACTIVE holds whose expires_at has passed".
CREATE INDEX ix_hold_status_expiry ON seat_hold (status, expires_at);

CREATE TABLE seat_hold_line (
    hold_id         VARCHAR2(36)   NOT NULL,
    seat_number     VARCHAR2(4)    NOT NULL,
    cabin_class     VARCHAR2(16)   NOT NULL,
    price_amount    NUMBER(12, 2)  NOT NULL,
    CONSTRAINT pk_seat_hold_line PRIMARY KEY (hold_id, seat_number),
    CONSTRAINT fk_hold_line_hold FOREIGN KEY (hold_id) REFERENCES seat_hold (id)
);
